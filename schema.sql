CREATE TABLE locations (
  location_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  location_name VARCHAR2(100) NOT NULL,
  latitude NUMBER(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude NUMBER(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  location_type VARCHAR2(20) NOT NULL CHECK (location_type IN ('WAREHOUSE','DISASTER_ZONE','HOSPITAL')));
CREATE INDEX idx_loc_coords ON locations (latitude, longitude);  -- composite B+ tree

CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(120) NOT NULL UNIQUE,
  role VARCHAR2(20) NOT NULL CHECK (role IN ('FIELD_RESPONDER','DISPATCHER','COMMANDER')),
  location_id NUMBER NOT NULL REFERENCES locations(location_id));

CREATE TABLE disaster_incidents (
  incident_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  title VARCHAR2(150) NOT NULL,
  severity_level NUMBER(1) NOT NULL CHECK (severity_level BETWEEN 1 AND 5),
  status VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE','CONTAINED','RESOLVED')),
  location_id NUMBER NOT NULL REFERENCES locations(location_id),
  reported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL);

CREATE TABLE resources (
  resource_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  resource_name VARCHAR2(100) NOT NULL,
  resource_type VARCHAR2(20) NOT NULL CHECK (resource_type IN ('MEDICAL','VEHICLE','EQUIPMENT','FOOD_WATER')),
  total_qty NUMBER NOT NULL CHECK (total_qty >= 0),
  available_qty NUMBER NOT NULL,
  location_id NUMBER NOT NULL REFERENCES locations(location_id),
  CONSTRAINT ck_avail CHECK (available_qty BETWEEN 0 AND total_qty));

CREATE TABLE medical_supplies (   -- ISA subclass of RESOURCES
  resource_id NUMBER PRIMARY KEY REFERENCES resources(resource_id) ON DELETE CASCADE,
  is_cold_chain NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_cold_chain IN (0,1)),
  storage_temp_celsius NUMBER(4) CHECK (storage_temp_celsius BETWEEN -80 AND 45),
  expiry_date DATE NOT NULL,
  CONSTRAINT ck_cold_temp CHECK (is_cold_chain = 0 OR storage_temp_celsius IS NOT NULL));

CREATE TABLE resource_requests (
  request_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  incident_id NUMBER NOT NULL REFERENCES disaster_incidents(incident_id),
  resource_id NUMBER NOT NULL REFERENCES resources(resource_id),
  requested_by NUMBER NOT NULL REFERENCES users(user_id),
  requested_qty NUMBER NOT NULL CHECK (requested_qty > 0),
  priority_score NUMBER(6,2) NOT NULL,
  status VARCHAR2(10) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','FULFILLED','REJECTED')),
  requested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL);
CREATE INDEX idx_req_queue ON resource_requests (status, priority_score DESC);

CREATE TABLE dispatch_allocations (   -- audit log
  allocation_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  request_id NUMBER NOT NULL UNIQUE REFERENCES resource_requests(request_id),
  dispatched_by NUMBER NOT NULL REFERENCES users(user_id),
  allocated_qty NUMBER NOT NULL CHECK (allocated_qty > 0),
  dispatched_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL);

-- Supports joins and deletes through the resource-to-location foreign key.
CREATE INDEX idx_res_loc ON resources(location_id);
-- Supports stock/priority reservation checks during fulfillment.
CREATE INDEX idx_req_res_status ON resource_requests(resource_id,status,priority_score);
-- Supports incident request listings and automatic rejection on resolution.
CREATE INDEX idx_req_incident ON resource_requests(incident_id,status);
-- Supports allocation history lookups by dispatcher.
CREATE INDEX idx_alloc_by ON dispatch_allocations(dispatched_by);
-- Supports location-based user lookup and foreign-key maintenance.
CREATE INDEX idx_users_loc ON users(location_id);

CREATE OR REPLACE TRIGGER trg_med_isa
BEFORE INSERT OR UPDATE ON medical_supplies FOR EACH ROW
DECLARE v_type resources.resource_type%TYPE;
BEGIN
  SELECT resource_type INTO v_type FROM resources WHERE resource_id=:NEW.resource_id;
  IF v_type <> 'MEDICAL' THEN RAISE_APPLICATION_ERROR(-20010,'Medical supplies must reference a MEDICAL resource.'); END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_res_type_guard
BEFORE UPDATE OF resource_type ON resources FOR EACH ROW
DECLARE v_count NUMBER;
BEGIN
  IF :OLD.resource_type='MEDICAL' AND :NEW.resource_type<>'MEDICAL' THEN
    SELECT COUNT(*) INTO v_count FROM medical_supplies WHERE resource_id=:OLD.resource_id;
    IF v_count>0 THEN RAISE_APPLICATION_ERROR(-20011,'Remove medical subtype before changing resource type.'); END IF;
  END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_alloc_immutable
BEFORE UPDATE OR DELETE ON dispatch_allocations FOR EACH ROW
BEGIN RAISE_APPLICATION_ERROR(-20001,'Audit log is immutable'); END;
/

-- Atomic allocation: strict 2PL with row locks, concurrency handled INSIDE the database.
CREATE OR REPLACE PROCEDURE sp_fulfill_request(
  p_request_id IN NUMBER, p_dispatcher_id IN NUMBER,
  p_override IN NUMBER DEFAULT 0,
  o_code OUT VARCHAR2, o_msg OUT VARCHAR2) AS
  v_req   resource_requests%ROWTYPE;
  v_avail resources.available_qty%TYPE;
  v_role  users.role%TYPE;
  v_exp   DATE;
  v_incident_status disaster_incidents.status%TYPE;
  v_reserved NUMBER := 0;
  v_reserved_count NUMBER := 0;
  c_critical CONSTANT NUMBER := 100; -- Critical triage requests may wait for stock.
  e_busy EXCEPTION; PRAGMA EXCEPTION_INIT(e_busy,-54);
  e_timeout EXCEPTION; PRAGMA EXCEPTION_INIT(e_timeout,-30006);
  e_deadlock EXCEPTION; PRAGMA EXCEPTION_INIT(e_deadlock,-60);
BEGIN
  SELECT role INTO v_role FROM users WHERE user_id = p_dispatcher_id;
  IF v_role NOT IN ('DISPATCHER','COMMANDER') THEN
    o_code := 'FORBIDDEN'; o_msg := 'Only dispatchers or commanders can fulfill requests.'; RETURN;
  END IF;
  SELECT * INTO v_req FROM resource_requests WHERE request_id = p_request_id FOR UPDATE;
  IF v_req.status <> 'PENDING' THEN
    ROLLBACK; o_code := 'ALREADY_DONE'; o_msg := 'Request is already ' || v_req.status || '.'; RETURN;
  END IF;
  SELECT status INTO v_incident_status FROM disaster_incidents WHERE incident_id=v_req.incident_id;
  IF v_incident_status='RESOLVED' THEN ROLLBACK; o_code:='INCIDENT_CLOSED'; o_msg:='Incident is resolved.'; RETURN; END IF;
  IF p_override=1 AND v_role<>'COMMANDER' THEN ROLLBACK; o_code:='FORBIDDEN'; o_msg:='Only a commander may override priority holds.'; RETURN; END IF;
  IF v_req.priority_score >= c_critical THEN
    SELECT available_qty INTO v_avail FROM resources WHERE resource_id=v_req.resource_id FOR UPDATE WAIT 10;
  ELSE
    SELECT available_qty INTO v_avail FROM resources WHERE resource_id=v_req.resource_id FOR UPDATE NOWAIT;
  END IF;
  SELECT NVL(SUM(requested_qty),0),COUNT(*) INTO v_reserved,v_reserved_count FROM resource_requests
   WHERE resource_id=v_req.resource_id AND status='PENDING' AND request_id<>p_request_id
     AND priority_score>v_req.priority_score;
  IF (v_avail-v_reserved)<v_req.requested_qty AND p_override=0 THEN
    ROLLBACK; o_code:='PRIORITY_HOLD'; o_msg:='Stock is reserved for '||v_reserved_count||' higher-priority request(s).'; RETURN;
  END IF;
  BEGIN
    SELECT expiry_date INTO v_exp FROM medical_supplies WHERE resource_id = v_req.resource_id;
  EXCEPTION WHEN NO_DATA_FOUND THEN v_exp := NULL;
  END;
  IF v_exp IS NOT NULL AND v_exp < TRUNC(SYSDATE) THEN
    ROLLBACK; o_code := 'EXPIRED'; o_msg := 'Stock has expired and cannot be dispatched.'; RETURN;
  END IF;
  IF v_avail < v_req.requested_qty THEN
    ROLLBACK; o_code := 'INSUFFICIENT'; o_msg := 'Only ' || v_avail || ' units available.'; RETURN;
  END IF;
  UPDATE resources SET available_qty = available_qty - v_req.requested_qty WHERE resource_id = v_req.resource_id;
  UPDATE resource_requests SET status = 'FULFILLED' WHERE request_id = p_request_id;
  INSERT INTO dispatch_allocations (request_id, dispatched_by, allocated_qty)
    VALUES (p_request_id, p_dispatcher_id, v_req.requested_qty);
  COMMIT;
  o_code := 'OK'; o_msg := 'Dispatched ' || v_req.requested_qty || ' units.';
EXCEPTION
  WHEN NO_DATA_FOUND THEN ROLLBACK; o_code := 'NOT_FOUND'; o_msg := 'Request or user not found.';
  WHEN e_busy OR e_timeout THEN ROLLBACK; o_code:='BUSY_RETRY'; o_msg:='Stock is being allocated by another dispatcher, retry.';
  WHEN e_deadlock THEN ROLLBACK; o_code:='DEADLOCK_RETRY'; o_msg:='Deadlock detected; retry this request.';
  WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_reject_request(p_request_id IN NUMBER,p_dispatcher_id IN NUMBER,o_code OUT VARCHAR2,o_msg OUT VARCHAR2) AS
 v_role users.role%TYPE; v_status resource_requests.status%TYPE;
BEGIN
 SELECT role INTO v_role FROM users WHERE user_id=p_dispatcher_id;
 IF v_role NOT IN ('DISPATCHER','COMMANDER') THEN o_code:='FORBIDDEN'; o_msg:='Dispatcher or commander required.'; RETURN; END IF;
 SELECT status INTO v_status FROM resource_requests WHERE request_id=p_request_id FOR UPDATE;
 IF v_status<>'PENDING' THEN ROLLBACK; o_code:='ALREADY_DONE'; o_msg:='Request is not pending.'; RETURN; END IF;
 UPDATE resource_requests SET status='REJECTED' WHERE request_id=p_request_id; COMMIT; o_code:='OK'; o_msg:='Request rejected.';
EXCEPTION WHEN NO_DATA_FOUND THEN ROLLBACK; o_code:='NOT_FOUND'; o_msg:='Request or dispatcher not found.';
 WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_process_queue(p_dispatcher_id IN NUMBER,o_processed OUT NUMBER,o_summary OUT VARCHAR2,o_code OUT VARCHAR2) AS
 TYPE ids_t IS TABLE OF NUMBER; ids ids_t; v_code VARCHAR2(30); v_msg VARCHAR2(300);
 TYPE counts_t IS TABLE OF PLS_INTEGER INDEX BY VARCHAR2(30); counts counts_t; k VARCHAR2(30);
 v_role users.role%TYPE;
BEGIN
 SELECT role INTO v_role FROM users WHERE user_id=p_dispatcher_id;
 IF v_role NOT IN ('DISPATCHER','COMMANDER') THEN o_processed:=0; o_summary:='Dispatcher or commander role required.'; o_code:='FORBIDDEN'; RETURN; END IF;
 SELECT request_id BULK COLLECT INTO ids FROM resource_requests WHERE status='PENDING' ORDER BY priority_score DESC,requested_at;
 o_processed:=0; o_summary:=''; o_code:='OK';
 FOR i IN 1..ids.COUNT LOOP
  sp_fulfill_request(ids(i),p_dispatcher_id,0,v_code,v_msg);
  IF v_code='OK' THEN o_processed:=o_processed+1; END IF;
  IF counts.EXISTS(v_code) THEN counts(v_code):=counts(v_code)+1; ELSE counts(v_code):=1; END IF;
 END LOOP;
 k:=counts.FIRST; WHILE k IS NOT NULL LOOP
   IF o_summary IS NOT NULL AND LENGTH(o_summary)>0 THEN o_summary:=o_summary||', '; END IF;
   o_summary:=o_summary||k||'='||counts(k); k:=counts.NEXT(k);
 END LOOP;
 IF o_summary IS NULL OR o_summary='' THEN o_summary:='No pending requests.'; END IF;
EXCEPTION WHEN NO_DATA_FOUND THEN o_processed:=0; o_summary:='Dispatcher not found.'; o_code:='NOT_FOUND';
END;
/

CREATE OR REPLACE PROCEDURE sp_allocate_nearest(
 p_incident_id IN NUMBER,p_resource_type IN VARCHAR2,p_qty IN NUMBER,p_requested_by IN NUMBER,
 p_dispatcher_id IN NUMBER,p_radius_km IN NUMBER,o_code OUT VARCHAR2,o_msg OUT VARCHAR2,
 o_resource_id OUT NUMBER,o_distance_km OUT NUMBER) AS
 v_lat NUMBER; v_lng NUMBER; v_sev NUMBER; v_ulat NUMBER; v_ulng NUMBER; v_status VARCHAR2(15);
 v_res_id NUMBER; v_loc_id NUMBER; v_name VARCHAR2(100); v_avail NUMBER; v_dist NUMBER; v_score NUMBER;
 v_reserved NUMBER; v_found BOOLEAN:=FALSE;
 v_role VARCHAR2(20); v_new_req NUMBER;
 CURSOR c_near IS
  SELECT r.resource_id,r.location_id,r.resource_name,r.available_qty,
   6371*ACOS(LEAST(1,GREATEST(-1,SIN(v_lat*ACOS(-1)/180)*SIN(l.latitude*ACOS(-1)/180)+COS(v_lat*ACOS(-1)/180)*COS(l.latitude*ACOS(-1)/180)*COS((l.longitude-v_lng)*ACOS(-1)/180)))) distance_km
  FROM resources r JOIN locations l ON l.location_id=r.location_id
  WHERE r.resource_type=p_resource_type AND r.available_qty>=p_qty
   AND (r.resource_type<>'MEDICAL' OR NOT EXISTS
        (SELECT 1 FROM medical_supplies m WHERE m.resource_id=r.resource_id AND m.expiry_date<TRUNC(SYSDATE)))
   AND l.latitude BETWEEN v_lat-p_radius_km/111 AND v_lat+p_radius_km/111
   AND l.longitude BETWEEN v_lng-p_radius_km/(111.32*GREATEST(0.01,COS(v_lat*ACOS(-1)/180))) AND v_lng+p_radius_km/(111.32*GREATEST(0.01,COS(v_lat*ACOS(-1)/180)))
   AND 6371*ACOS(LEAST(1,GREATEST(-1,SIN(v_lat*ACOS(-1)/180)*SIN(l.latitude*ACOS(-1)/180)+COS(v_lat*ACOS(-1)/180)*COS(l.latitude*ACOS(-1)/180)*COS((l.longitude-v_lng)*ACOS(-1)/180))))<=p_radius_km
  ORDER BY distance_km FOR UPDATE OF r.available_qty SKIP LOCKED;
BEGIN
 o_resource_id:=NULL; o_distance_km:=NULL;
 SELECT role INTO v_role FROM users WHERE user_id=p_dispatcher_id;
 IF v_role NOT IN ('DISPATCHER','COMMANDER') THEN o_code:='FORBIDDEN'; o_msg:='Dispatcher or commander required.'; RETURN; END IF;
 SELECT i.status,i.severity_level,l.latitude,l.longitude INTO v_status,v_sev,v_lat,v_lng FROM disaster_incidents i JOIN locations l ON l.location_id=i.location_id WHERE i.incident_id=p_incident_id;
 IF v_status<>'ACTIVE' THEN o_code:='INCIDENT_CLOSED'; o_msg:='Incident must be active.'; RETURN; END IF;
 OPEN c_near;
 LOOP
  FETCH c_near INTO v_res_id,v_loc_id,v_name,v_avail,v_dist;
  EXIT WHEN c_near%NOTFOUND;
  -- Mirrors server.js priority formula: severity*20 plus a distance bonus, rounded to 2 decimals.
  v_score:=ROUND(v_sev*20+GREATEST(0,50-v_dist/10),2);
  SELECT NVL(SUM(requested_qty),0) INTO v_reserved FROM resource_requests
   WHERE resource_id=v_res_id AND status='PENDING' AND priority_score>v_score;
  IF v_avail-v_reserved>=p_qty THEN v_found:=TRUE; EXIT; END IF;
 END LOOP;
 CLOSE c_near;
 IF NOT v_found THEN ROLLBACK; o_code:='NONE_AVAILABLE'; o_msg:='No matching stock is available within the radius; matching stock is reserved for higher-priority requests.'; RETURN; END IF;
 INSERT INTO resource_requests(incident_id,resource_id,requested_by,requested_qty,priority_score,status)
 VALUES(p_incident_id,v_res_id,p_requested_by,p_qty,v_score,'FULFILLED') RETURNING request_id INTO v_new_req;
 UPDATE resources SET available_qty=available_qty-p_qty WHERE resource_id=v_res_id;
 INSERT INTO dispatch_allocations(request_id,dispatched_by,allocated_qty) VALUES(v_new_req,p_dispatcher_id,p_qty);
 COMMIT; o_code:='OK'; o_msg:='Allocated '||p_qty||' units from '||v_name||'.'; o_resource_id:=v_res_id; o_distance_km:=ROUND(v_dist,1);
EXCEPTION WHEN NO_DATA_FOUND THEN ROLLBACK; o_code:='NOT_FOUND'; o_msg:='Incident, user, or dispatcher not found.';
 WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_set_incident_status(p_incident_id IN NUMBER,p_user_id IN NUMBER,p_status IN VARCHAR2,o_code OUT VARCHAR2,o_msg OUT VARCHAR2) AS
 v_role users.role%TYPE; v_old disaster_incidents.status%TYPE;
BEGIN
 SELECT role INTO v_role FROM users WHERE user_id=p_user_id;
 IF v_role<>'COMMANDER' THEN o_code:='FORBIDDEN'; o_msg:='Commander role required.'; RETURN; END IF;
 SELECT status INTO v_old FROM disaster_incidents WHERE incident_id=p_incident_id FOR UPDATE;
 IF NOT ((v_old='ACTIVE' AND p_status='CONTAINED') OR (v_old='CONTAINED' AND p_status IN ('ACTIVE','RESOLVED'))) THEN o_code:='INVALID_TRANSITION'; o_msg:='Incident status transition is not allowed.'; ROLLBACK; RETURN; END IF;
 UPDATE disaster_incidents SET status=p_status WHERE incident_id=p_incident_id;
 IF p_status='RESOLVED' THEN UPDATE resource_requests SET status='REJECTED' WHERE incident_id=p_incident_id AND status='PENDING'; END IF;
 COMMIT; o_code:='OK'; o_msg:='Incident status updated.';
EXCEPTION WHEN NO_DATA_FOUND THEN ROLLBACK; o_code:='NOT_FOUND'; o_msg:='Incident or commander not found.';
 WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/

